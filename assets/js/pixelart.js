const COLORS = { '#': '#f2f2f2', '+': '#6f6f6f', r: '#e0443a' };

export function pixelIcon(name, size = 96) {
  const grid = ART[name] || ART.knight;
  let rects = '';
  grid.forEach((row, y) => {
    [...row].forEach((ch, x) => {
      if (COLORS[ch]) rects += `<rect x="${x}" y="${y}" width="1.02" height="1.02" fill="${COLORS[ch]}"/>`;
    });
  });
  return `<svg viewBox="0 0 12 12" width="${size}" height="${size}" shape-rendering="crispEdges" aria-hidden="true">${rects}</svg>`;
}
